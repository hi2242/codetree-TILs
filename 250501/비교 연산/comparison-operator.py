A, B = map(int, input().split())

# A가 B보다 같거나 큰가?
if A >= B:
    print(1)
else:
    print(0)

# A가 B보다 큰가?
if A > B:
    print(1)
else:
    print(0)

# B가 A보다 같거나 큰가?
if B >= A:
    print(1)
else:
    print(0)

# B가 A보다 큰가?
if B > A:
    print(1)
else:
    print(0)

# A와 B가 같은가?
if A == B:
    print(1)
else:
    print(0)

# A와 B가 다른가?
if A != B:
    print(1)
else:
    print(0)